public class Resta {
    /**
     * Este metodo recibe dos operandos enteros y devuelve su diferencia
     * @return la resta de op1 y op2
     * @param op1 primer operando
     * @param op2 segundo operando
     */
    public static int realizarOperacion(int op1, int op2){return op1-op2;}
}
